<?php

namespace Database\Seeders;

use App\Models\AnnualFinancial;
use App\Models\Comment;
use App\Models\Component;
use App\Models\District;
use App\Models\ExtensionRequest;
use App\Models\FinancialReport;
use App\Models\FinancialYear;
use App\Models\FinancingAgreement;
use App\Models\Issue;
use App\Models\Meeting;
use App\Models\Organization;
use App\Models\PipelineStepTemplate;
use App\Models\Project;
use App\Models\ProjectCostVersion;
use App\Models\ProjectPipelineStep;
use App\Models\QuarterlyFinancial;
use App\Models\ReportingPeriod;
use App\Models\Role;
use App\Models\Sector;
use App\Models\Subcomponent;
use App\Models\User;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;
use RuntimeException;

class TestingDataSeeder extends Seeder
{
    public function run(): void
    {
        if (app()->environment('production')) {
            throw new RuntimeException('TestingDataSeeder cannot run in production.');
        }
        $this->call([UserSeeder::class, DistrictSeeder::class, PipelineTemplateSeeder::class]);
        DB::transaction(function (): void {
            DB::table('currencies')->insertOrIgnore(['code' => 'PKR', 'name' => 'Pakistan rupee', 'decimal_places' => 2]);
            $directors = [];
            foreach ([1, 2] as $number) {
                $user = User::firstOrNew(['email' => 'director'.$number.'@example.test']);
                if (! $user->exists) {
                    $user->forceFill(['name' => 'TEST Project Director '.$number, 'password' => 'TestingDirector@12345', 'role_id' => Role::where('name', 'Project Director')->sole()->id, 'account_status' => 'Active'])->save();
                }
                $directors[] = $user;
            }
            $reviewer = User::where('email', 'admin@ids.local')->sole();
            $districts = District::where('code', '!=', 'MULTI')->orderBy('name')->get();
            $names = ['Community Schools', 'District Health Facilities', 'Rural Roads', 'Drinking Water', 'Flood Protection', 'Skills Development', 'Solar Energy', 'Irrigation Rehabilitation', 'Digital Services', 'Agricultural Support'];
            foreach ($names as $index => $name) {
                $number = $index + 1;
                $reference = sprintf('TEST-IDS-%03d', $number);
                if (Project::where('reference_code', $reference)->exists()) {
                    continue;
                }
                $sectorName = ['Education', 'Health', 'Transport', 'Water', 'Energy'][$index % 5];
                $sector = Sector::firstOrCreate(['code' => 'TEST-'.strtoupper($sectorName)], ['name' => 'TEST '.$sectorName, 'active' => true]);
                $donor = Organization::firstOrCreate(['code' => 'TEST-PARTNER-'.($index % 3 + 1)], ['name' => 'TEST Development Partner '.($index % 3 + 1), 'organization_type' => 'Donor', 'active' => true]);
                $director = $directors[$index % 2];
                $pipeline = $number <= 4;
                $project = new Project;
                $project->forceFill(['reference_code' => $reference, 'name' => 'TEST '.$name, 'objective' => 'Fictional project for quality assurance and user acceptance testing. Not official project data.', 'phase' => $pipeline ? 'Pipeline' : 'Ongoing', 'lifecycle' => 'Active', 'sector_id' => $sector->id, 'district_id' => $districts[$index]->id, 'project_director_id' => $director->id, 'implementing_agency' => 'TEST Implementation Unit', 'funding_type' => ['Grant', 'Loan', 'Govt. share', 'Mixed'][$index % 4], 'is_flagship' => $number <= 3, 'start_date' => today()->subMonths(6), 'original_end_date' => today()->addYears(2), 'current_end_date' => today()->addYears(2), 'source_notes' => 'Generated by TestingDataSeeder.'])->save();
                $project->districts()->attach($districts[$index]->id);
                if ($number % 3 === 0) {
                    $project->districts()->attach($districts[$index + 1]->id);
                }
                DB::table('project_organizations')->insert(['project_id' => $project->id, 'organization_id' => $donor->id, 'role' => 'donor']);
                DB::table('project_assignments')->insert(['project_id' => $project->id, 'user_id' => $reviewer->id, 'assignment_role' => 'Extension approver', 'can_approve_extension' => true]);
                if ($pipeline) {
                    foreach (PipelineStepTemplate::where('active', true)->orderBy('sort_order')->take(5)->get() as $offset => $template) {
                        ProjectPipelineStep::create(['project_id' => $project->id, 'template_id' => $template->id, 'name' => $template->name, 'sort_order' => $template->sort_order, 'status' => $offset === 0 ? 'Done' : ($offset === 1 ? 'In progress' : 'Not started'), 'is_current' => $offset === 1, 'start_date' => today()->subMonths(3), 'planned_date' => $number === 1 && $offset === 1 ? today()->subDays(10) : today()->addDays(30 * ($offset + 1)), 'completed_date' => $offset === 0 ? today()->subDays(20) : null, 'responsible_office' => 'TEST Planning Office']);
                    }
                } else {
                    $this->seedComponents($project, $director, $reviewer, $number);
                    $this->seedFinances($project, $donor, $reviewer, $number);
                }
                foreach (range(1, $number === 5 ? 4 : 1) as $issueNumber) {
                    Issue::create(['source_key' => $reference.'-ISSUE-'.$issueNumber, 'project_id' => $project->id, 'pipeline_step_id' => $pipeline ? $project->pipelineSteps()->where('is_current', true)->value('id') : null, 'component_id' => $pipeline ? null : $project->components()->value('id'), 'title' => 'TEST '.$reference.' issue '.$issueNumber, 'description' => 'Sample issue for testing project issue lists and resolution.', 'status' => $number % 2 === 0 ? 'Resolved' : 'Open', 'due_date' => today()->addDays(14)]);
                }
                $comment = Comment::create(['project_id' => $project->id, 'author_id' => $director->id, 'body' => 'TEST: Please review the project progress and upcoming milestones.', 'version' => 1]);
                Comment::create(['project_id' => $project->id, 'parent_id' => $comment->id, 'author_id' => $reviewer->id, 'body' => 'TEST reply: Review scheduled for the next coordination meeting.', 'version' => 1]);
                $meeting = Meeting::create(['name' => 'TEST '.$reference.' coordination meeting', 'scheduled_at' => $number <= 3 ? now()->subDays($number) : now()->addDays($number), 'location' => 'TEST Conference Room', 'agenda' => 'Review progress, financing, open issues and deadlines.', 'minutes' => $number <= 3 ? 'TEST minutes: follow up on milestones and pending issues.' : null, 'status' => $number <= 3 ? 'Held' : 'Scheduled', 'version' => 1]);
                $meeting->projects()->attach($project);
            }
        });
    }

    private function seedComponents(Project $project, User $director, User $reviewer, int $number): void
    {
        foreach (range(1, 6) as $sequence) {
            $deadline = $number % 2 === 1 && $sequence === 2 ? today()->subDays(7) : today()->addMonths($sequence);
            $component = Component::create(['project_id' => $project->id, 'sequence_no' => $sequence, 'name' => 'Component '.$sequence, 'start_date' => today()->subMonths(3), 'baseline_end' => $deadline, 'effective_end' => $deadline, 'lifecycle' => $sequence === 1 ? 'Completed' : ($sequence >= 5 ? 'Not started' : 'Ongoing'), 'reported_progress' => $sequence === 1 ? 100 : ($sequence >= 5 ? 0 : 40), 'responsible_office' => 'TEST Works Office', 'version' => 1]);
            if ($sequence % 2 === 0) {
                foreach (range(1, $sequence === 4 ? 3 : 2) as $subsequence) {
                    Subcomponent::create(['component_id' => $component->id, 'sequence_no' => $subsequence, 'name' => 'Subcomponent '.$sequence.'.'.$subsequence, 'start_date' => $component->start_date, 'baseline_end' => $deadline, 'effective_end' => $deadline, 'lifecycle' => $component->lifecycle, 'reported_progress' => $component->reported_progress, 'responsible_office' => 'TEST Works Office', 'version' => 1]);
                }
            }
            if ($sequence === 2) {
                ExtensionRequest::create(['component_id' => $component->id, 'requester_id' => $director->id, 'reviewer_id' => $reviewer->id, 'old_end_date' => $deadline, 'requested_end_date' => $deadline->copy()->addDays(30), 'reason' => 'TEST: Additional time requested for material delivery.', 'impact' => 'Review the revised delivery milestone.', 'status' => 'Pending', 'target_version' => 1]);
            }
        }
    }

    private function seedFinances(Project $project, Organization $donor, User $reviewer, int $number): void
    {
        ProjectCostVersion::create(['project_id' => $project->id, 'version_no' => 1, 'currency_code' => 'PKR', 'total_cost' => 100000000 * $number, 'foreign_cost' => 60000000 * $number, 'local_cost' => 40000000 * $number]);
        $agreement = FinancingAgreement::create(['project_id' => $project->id, 'donor_id' => $donor->id, 'currency_code' => 'PKR', 'agreement_ref' => $project->reference_code.'-AGREEMENT', 'original_commitment' => 60000000 * $number, 'signing_date' => today()->subMonths(6), 'terms' => 'Fictional agreement for testing only.']);
        $currentYear = today()->month >= 7 ? today()->year : today()->year - 1;
        foreach ([$currentYear - 1, $currentYear] as $startYear) {
            $year = FinancialYear::firstOrCreate(['label' => $startYear.'-'.substr((string) ($startYear + 1), -2)], ['start_date' => $startYear.'-07-01', 'end_date' => ($startYear + 1).'-06-30']);
            $report = FinancialReport::create(['project_id' => $project->id, 'financial_year_id' => $year->id, 'as_of_date' => $startYear < $currentYear ? $year->end_date : today(), 'revision_no' => 1, 'currency_code' => 'PKR', 'source_notes' => 'Fictional, reconciled financial figures for testing.']);
            $elapsedQuarters = $startYear < $currentYear ? 4 : intdiv((today()->month + 5) % 12, 3) + 1;
            AnnualFinancial::create(['report_id' => $report->id, 'currency_code' => 'PKR', 'total_allocation' => 20000000, 'expenditure_ytd' => 1250000 * $elapsedQuarters, 'cumulative_expenditure' => 10000000, 'disbursement_target' => 20000000, 'disbursement_ytd' => 1500000 * $elapsedQuarters]);
            foreach (range(1, 4) as $quarter) {
                $start = $year->start_date->copy()->addMonths(($quarter - 1) * 3);
                $period = ReportingPeriod::firstOrCreate(['financial_year_id' => $year->id, 'quarter_no' => $quarter], ['start_date' => $start, 'end_date' => $start->copy()->addMonths(3)->subDay()]);
                QuarterlyFinancial::create(['report_id' => $report->id, 'period_id' => $period->id, 'currency_code' => 'PKR', 'planned_disbursement' => 5000000, 'actual_disbursement' => $quarter <= $elapsedQuarters ? 1500000 : null, 'expenditure_amount' => $quarter <= $elapsedQuarters ? 1250000 : null]);
            }

        }
    }
}
